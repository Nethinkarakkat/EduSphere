def get_column_widths(report_type, doc_width=None):
    """
    Returns column width configuration for each report type.
    Widths are percentages of available page width.
    
    Args:
        report_type: Type of report ('users', 'activity', 'exam', etc.)
        doc_width: Available document width in points (optional)
    
    Returns list of column widths in points units.
    """
    # A4 width is approximately 595 points
    # With 35pt margins on each side, available width is ~525 points
    if doc_width is None:
        doc_width = 525  # Default A4 width with 35pt margins
    
    # Define column percentages for each report type
    if report_type == 'users':
        # Name: 24%, Email: 34%, Role: 12%, Status: 12%, Created: 18%
        percentages = [0.24, 0.34, 0.12, 0.12, 0.18]
    
    elif report_type == 'activity':
        # User: 18%, Role: 10%, Email: 28%, Action: 24%, Time: 20%
        percentages = [0.18, 0.10, 0.28, 0.24, 0.20]
    
    elif report_type == 'analytics':
        # Exam: 20%, Subject: 20%, Attempts: 10%, Average: 12%, Max: 8%, Min: 8%, Avg%: 12%, Date: 10%
        percentages = [0.20, 0.20, 0.10, 0.12, 0.08, 0.08, 0.12, 0.10]
    
    elif report_type == 'faculty_results':
        # Student: 20%, Exam: 18%, Subject: 12%, Date: 12%, Score: 10%, Total: 10%, %: 8%, Result: 10%
        percentages = [0.20, 0.18, 0.12, 0.12, 0.10, 0.10, 0.08, 0.10]
    
    elif report_type == 'student_results':
        # Exam: 22%, Subject: 18%, Faculty: 15%, Date: 12%, Score: 10%, Total: 10%, %: 8%, Result: 5%
        percentages = [0.22, 0.18, 0.15, 0.12, 0.10, 0.10, 0.08, 0.05]
    
    elif report_type == 'admin_reports':
        # Student: 20%, Exam: 18%, Subject: 12%, Faculty: 12%, Classroom: 10%, Date: 10%, Score: 8%, Total: 10%
        percentages = [0.20, 0.18, 0.12, 0.12, 0.10, 0.10, 0.08, 0.10]
    
    elif report_type == 'question_bank':
        # Question: 35%, Subject: 15%, Type: 12%, Marks: 10%, Difficulty: 10%, Actions: 18%
        percentages = [0.35, 0.15, 0.12, 0.10, 0.10, 0.18]
    
    elif report_type == 'integrity':
        # Student: 20%, Exam: 18%, Subject: 15%, Date: 12%, Flagged: 15%, Actions: 20%
        percentages = [0.20, 0.18, 0.15, 0.12, 0.15, 0.20]
    
    elif report_type == 'classroom':
        # Name: 25%, Registration: 15%, Email: 30%, Joined: 15%, Actions: 15%
        percentages = [0.25, 0.15, 0.30, 0.15, 0.15]
    
    else:
        # Default fallback
        percentages = [0.20] * 5
    
    # Calculate actual widths in points
    return [doc_width * pct for pct in percentages]


def create_header_table(title, generated_time, logo_path=None):
    """
    Creates a two-column header table.
    Left: Report title and generated timestamp
    Right: EduSphere branding and logo
    """
    styles = get_pdf_styles()
    
    # Left column: Title and timestamp
    left_content = [
        [Paragraph(title, styles['title'])],
        [Paragraph(f"Generated: {generated_time}", styles['subtitle'])]
    ]
    
    # Right column: EduSphere branding and logo
    if logo_path and os.path.exists(logo_path):
        logo = Image(logo_path, width=1.5*cm, height=1.5*cm)
        right_content = [
            [Paragraph('EduSphere', styles['header'])],
            [Paragraph('Examination System', styles['subtitle'])],
            [logo]
        ]
    else:
        right_content = [
            [Paragraph('EduSphere', styles['header'])],
            [Paragraph('Examination System', styles['subtitle'])]
        ]
    
    # Create two-column header table
    header_data = [
        [left_content, right_content]
    ]
    
    # Calculate column widths (50% each)
    doc_width = 525  # Available width with 35pt margins
    col_widths = [doc_width * 0.5, doc_width * 0.5]
    
    header_table = Table(header_data, colWidths=col_widths)
    header_table.setStyle(TableStyle([
        ('ALIGN', (0, 0), (0, -1), 'LEFT'),
        ('ALIGN', (1, 0), (1, -1), 'RIGHT'),
        ('VALIGN', (0, 0), (-1, -1), 'MIDDLE'),
        ('LEFTPADDING', (0, 0), (-1, -1), 0),
        ('RIGHTPADDING', (0, 0), (-1, -1), 0),
        ('TOPPADDING', (0, 0), (-1, -1), 0),
        ('BOTTOMPADDING', (0, 0), (-1, -1), 15),
        ('LINEABOVE', (0, 0), (-1, 0), 0.5, colors.lightgrey),
        ('LINEBELOW', (0, -1), (-1, -1), 0.5, colors.lightgrey),
    ]))
    
    return header_table


def create_summary_section(summary_items):
    """
    Creates a summary section with bullet/colon-separated list.
    summary_items should be a list of [label, value] pairs.
    """
    styles = get_pdf_styles()
    
    elements = []
    
    # Add heading
    elements.append(Paragraph('Report Summary', styles['section']))
    
    # Add summary items as bullet points
    for label, value in summary_items:
        text = f"• {label} : {value}"
        elements.append(Paragraph(text, styles['normal']))
    
    # Add generated timestamp
    elements.append(Paragraph(f"• Generated On : {datetime.now().strftime('%d %b %Y %H:%M')}", styles['normal']))
    
    return elements


def apply_column_alignment(table_style, column_configs):
    """
    Applies column-specific alignment settings.
    
    column_configs: list of dicts with keys:
        - 'align': 'LEFT', 'CENTER', or 'RIGHT'
    """
    for col_idx, config in enumerate(column_configs):
        align = config.get('align', 'LEFT')
        
        # Apply alignment to body rows (skip header row 0)
        table_style.add('ALIGN', (col_idx, 1), (col_idx, -1), align)
    
    return table_style


def build_report_pdf(title, headers, rows, generated_time, filename, 
                    landscape=False, summary_items=None, logo_path=None):
    """
    Shared PDF builder function for all non-result reports.
    
    Args:
        title: Report title (e.g., 'ACTIVITY LOG REPORT')
        headers: List of column headers
        rows: List of data rows (each row is a list of values)
        generated_time: Timestamp string for when report was generated
        filename: Output filename
        landscape: Whether to use landscape orientation (default: False)
        summary_items: Optional list of [label, value] pairs for summary section
        logo_path: Optional path to logo image
    
    Returns:
        Flask Response object with PDF data
    """
    from flask import Response
    from io import BytesIO
    
    styles = get_pdf_styles()
    
    # Create PDF buffer
    buffer = BytesIO()
    doc = create_pdf_document(buffer, landscape=landscape)
    
    elements = []
    
    # Add header
    header = create_header_table(title, generated_time, logo_path)
    elements.append(header)
    
    # Add summary section if provided
    if summary_items:
        summary_elements = create_summary_section(summary_items)
        elements.extend(summary_elements)
        elements.append(Paragraph('', styles['normal']))  # Spacer
    
    # Convert rows to Paragraph objects for text wrapping
    wrapped_rows = []
    for row in rows:
        wrapped_row = [Paragraph(str(cell), styles['normal']) if cell else Paragraph('', styles['normal']) for cell in row]
        wrapped_rows.append(wrapped_row)
    
    # Convert headers to Paragraph objects
    wrapped_headers = [Paragraph(str(h), styles['normal']) for h in headers]
    
    # Create table data
    table_data = [wrapped_headers] + wrapped_rows
    
    # Get column widths based on report type (infer from title)
    report_type = infer_report_type(title)
    col_widths = get_column_widths(report_type)
    
    # Create table
    table = Table(table_data, colWidths=col_widths)
    table.setStyle(get_table_style(len(headers)))
    
    elements.append(table)
    
    # Build PDF
    doc.build(elements)
    
    # Create response
    buffer.seek(0)
    response = Response(buffer.getvalue(), mimetype='application/pdf')
    response.headers['Content-Disposition'] = f'attachment; filename={filename}'
    
    return response


def infer_report_type(title):
    """
    Infers report type from title for column width configuration.
    """
    title_lower = title.lower()
    
    if 'user' in title_lower:
        return 'users'
    elif 'activity' in title_lower:
        return 'activity'
    elif 'analytics' in title_lower:
        return 'analytics'
    elif 'faculty result' in title_lower:
        return 'faculty_results'
    elif 'student result' in title_lower:
        return 'student_results'
    elif 'admin report' in title_lower:
        return 'admin_reports'
    elif 'question' in title_lower:
        return 'question_bank'
    elif 'integrity' in title_lower:
        return 'integrity'
    elif 'classroom' in title_lower:
        return 'classroom'
    else:
        return 'users'  # Default fallback
