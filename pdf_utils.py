# Global variables for footer
_footer_generated_time = None
_footer_title = None


def set_footer_metadata(title, time_str):
    """Set the title and generated time for the footer."""
    global _footer_title, _footer_generated_time
    _footer_title = title
    _footer_generated_time = time_str


class NumberedCanvas(pdf_canvas.Canvas):
    """
    Canvas that does a two-pass render so the footer can show the true
    total page count, e.g. 'Page 2 of 5', instead of just the current page.
    """

    def __init__(self, *args, **kwargs):
        pdf_canvas.Canvas.__init__(self, *args, **kwargs)
        self._saved_page_states = []

    def showPage(self):
        # Defer actually finishing the page until we know the total count
        self._saved_page_states.append(dict(self.__dict__))
        self._startPage()

    def save(self):
        total_pages = len(self._saved_page_states)
        for state in self._saved_page_states:
            self.__dict__.update(state)
            self._draw_footer(total_pages)
            pdf_canvas.Canvas.showPage(self)
        pdf_canvas.Canvas.save(self)

    def _draw_footer(self, total_pages):
        """Draw the single-line, centered page-bottom footer, matching the
        approved reference design: 'Generated by EduSphere Examination
        System | Page X of Y | Generated on: <date time>'."""
        self.saveState()

        pagesize = self._pagesize
        width = pagesize[0]

        self.setFont('Helvetica', 8)
        self.setFillColor(colors.HexColor('#777777'))

        page_num = self._pageNumber
        generated_date = datetime.now().strftime('%d %b %Y')
        generated_time = datetime.now().strftime('%I:%M %p')

        footer_text = (
            f"Generated by EduSphere Examination System  |  "
            f"Page {page_num} of {total_pages}  |  "
            f"Generated on: {generated_date} {generated_time}"
        )
        self.drawCentredString(width / 2, 18, footer_text)

        self.restoreState()


