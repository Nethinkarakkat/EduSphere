def get_pdf_config(landscape=False):
    """
    Returns shared PDF configuration.
    Uses A4 portrait or landscape with consistent margins.
    """
    pagesize = A4
    if landscape:
        pagesize = (A4[1], A4[0])  # Swap for landscape
    
    return {
        'pagesize': pagesize,
        'left_margin': 35,
        'right_margin': 35,
        'top_margin': 40,
        'bottom_margin': 35,
    }


def create_pdf_document(response, landscape=False):
    """
    Creates a SimpleDocTemplate with shared configuration.
    """
    config = get_pdf_config(landscape=landscape)
    doc = SimpleDocTemplate(
        response,
        pagesize=config['pagesize'],
        leftMargin=config['left_margin'],
        rightMargin=config['right_margin'],
        topMargin=config['top_margin'],
        bottomMargin=config['bottom_margin'],
        onFirstPage=add_footer,
        onLaterPages=add_footer
    )
    return doc


def add_footer(canvas, doc):
    """Add standardized footer with page numbers."""
    canvas.saveState()
    canvas.setFont('Helvetica', 8)
    canvas.setFillColor(colors.grey)
    
    # Draw separator line
    canvas.setStrokeColor(colors.lightgrey)
    canvas.setLineWidth(0.5)
    canvas.line(35, 25, A4[0] - 35, 25)
    
    # Draw footer text
    page_num = canvas.getPageNumber()
    canvas.setFillColor(colors.grey)
    canvas.drawCentredString(
        A4[0] / 2,
        15,
        "Generated by EduSphere Examination System"
    )
    canvas.drawCentredString(
        A4[0] / 2,
        8,
        "This document is electronically generated and does not require a signature."
    )
    canvas.drawRightString(
        A4[0] - 35,
        8,
        f"Page {page_num}"
    )
    
    canvas.restoreState()


