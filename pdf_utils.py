def create_report_header(title, logo_path, doc_width):
    """
    Create the report header with a title that is truly centered on the
    full page width, and a logo + "EduSphere" brand block in the top-right
    corner. The logo and text are stacked inside a single fixed-width inner
    table so they share the same center line and stay aligned with each
    other.
    
    Args:
        title: Report title (e.g., 'USERS REPORT')
        logo_path: Path to logo image (optional)
        doc_width: Available document width
    
    Returns:
        Table object for the header
    """
    styles = get_styles()
    
    # Centered title paragraph
    title_paragraph = Paragraph(title.upper(), styles['title'])
    
    # Fixed-width brand column (used on both sides so the title column
    # in between is perfectly centered on the full page).
    brand_col_width = 3.4 * cm
    
    # Logo + "EduSphere" stacked inside a single narrow inner table so
    # both share the exact same width and center line.
    if logo_path and os.path.exists(logo_path):
        logo = Image(logo_path, width=2.1*cm, height=2.1*cm)
        brand_block = Table(
            [[logo], [Spacer(1, 4)], [Paragraph('EduSphere', styles['header_brand'])]],
            colWidths=[brand_col_width]
        )
    else:
        brand_block = Table(
            [[Paragraph('EduSphere', styles['header_brand'])]],
            colWidths=[brand_col_width]
        )
    brand_block.setStyle(TableStyle([
        ('ALIGN', (0, 0), (-1, -1), 'CENTER'),
        ('VALIGN', (0, 0), (-1, -1), 'MIDDLE'),
        ('LEFTPADDING', (0, 0), (-1, -1), 0),
        ('RIGHTPADDING', (0, 0), (-1, -1), 0),
        ('TOPPADDING', (0, 0), (-1, -1), 0),
        ('BOTTOMPADDING', (0, 0), (-1, -1), 0),
    ]))
    
    # 3-column header: empty spacer (left) - title (center) - brand block (right).
    # The spacer matches the brand column's width so the title is centered
    # on the full page, not just within a left-hand region.
    header_data = [['', title_paragraph, brand_block]]
    header_table = Table(
        header_data,
        colWidths=[brand_col_width, doc_width - (2 * brand_col_width), brand_col_width]
    )
    header_table.setStyle(TableStyle([
        ('ALIGN', (0, 0), (0, -1), 'LEFT'),
        ('ALIGN', (1, 0), (1, -1), 'CENTER'),
        ('ALIGN', (2, 0), (2, -1), 'RIGHT'),
        ('VALIGN', (0, 0), (-1, -1), 'MIDDLE'),
        ('LEFTPADDING', (0, 0), (-1, -1), 0),
        ('RIGHTPADDING', (0, 0), (-1, -1), 0),
        ('TOPPADDING', (0, 0), (-1, -1), 0),
        ('BOTTOMPADDING', (0, 0), (-1, -1), 25),
        ('LINEBELOW', (0, -1), (-1, -1), 0.8, colors.HexColor('#DDDDDD')),
    ]))
    
    return header_table


def create_summary_section(summary, doc_width):
    """
    Create the summary section: heading flush-left, with an indented
    label:value block underneath (matches the approved reference design).
    
    Args:
        summary: List of [label, value] pairs
        doc_width: Available document width
    
    Returns:
        List of flowables for the summary section
    """
    styles = get_styles()
    elements = []
    
    # Summary heading
    elements.append(Paragraph('SUMMARY', styles['section']))
    
    # Indented label:value block - label column starts ~30% into the
    # content width, distinguishing it from the flush-left table below.
    indent_w = doc_width * 0.30
    label_w = doc_width * 0.22
    value_w = doc_width - indent_w - label_w

    def add_summary_row(label, value):
        row_data = [[
            '',
            Paragraph(f"<b>{label}:</b>", styles['summary_label']),
            Paragraph(str(value), styles['summary_value'])
        ]]
        row_table = Table(row_data, colWidths=[indent_w, label_w, value_w])
        row_table.setStyle(TableStyle([
            ('ALIGN', (0, 0), (-1, -1), 'LEFT'),
            ('VALIGN', (0, 0), (-1, -1), 'MIDDLE'),
            ('LEFTPADDING', (0, 0), (-1, -1), 0),
            ('RIGHTPADDING', (0, 0), (-1, -1), 0),
            ('TOPPADDING', (0, 0), (-1, -1), 2),
            ('BOTTOMPADDING', (0, 0), (-1, -1), 2),
            ('GRID', (0, 0), (-1, -1), 0, colors.white),
        ]))
        elements.append(row_table)

    for label, value in summary:
        add_summary_row(label, value)
    
    # Add generated timestamp as a single combined row
    generated_date = datetime.now().strftime('%d %b %Y')
    generated_time = datetime.now().strftime('%I:%M %p')
    add_summary_row('Generated', f"{generated_date} {generated_time}")
    
    # Spacer before table
    elements.append(Spacer(1, 18))
    
    return elements


def get_column_alignment(header_name):
    """
    Determine appropriate alignment based on column header name.
    
    Args:
        header_name: The column header string
    
    Returns:
        Alignment string ('LEFT', 'CENTER', or 'RIGHT')
    """
    header_lower = header_name.lower()
    
    # Center-align these columns
    center_columns = ['status', 'role', 'score', 'total', '%', 'result', 'percentage', 
                      'date', 'time', 'attempts', 'avg', 'max', 'min', 'count', 'id']
    
    # Right-align numeric columns
    right_columns = ['amount', 'price', 'cost', 'value']
    
    for col in center_columns:
        if col in header_lower:
            return 'CENTER'
    
    for col in right_columns:
        if col in header_lower:
            return 'RIGHT'
    
    # Default to left for names, emails, descriptions
    return 'LEFT'


def _fit_table_layout(headers, rows, doc_width):
    """
    Compute column widths and a font size so every header and every cell
    fits on a single line - no wrapped/broken words like 'Attempt s'.
    
    Strategy: measure the natural (unwrapped) text width of every header
    and every cell, size each column to its widest content, then if the
    total is wider than the page, shrink header/body font sizes together
    (in 0.5pt steps) and re-measure until it fits or a readable floor is
    reached. Only as a last-resort fallback (extremely long content even
    at minimum font size) do columns get proportionally compressed.
    
    Args:
        headers: List of column headers
        rows: List of data rows
        doc_width: Available document width
    
    Returns:
        (col_widths, header_font_size, body_font_size)
    """
    header_font = 'Helvetica-Bold'
    body_font = 'Helvetica'
    cell_padding = 20  # matches LEFTPADDING(10) + RIGHTPADDING(10) used below

    default_header_size = 11
    default_body_size = 10
    min_header_size = 8
    min_body_size = 7

    def measure(h_size, b_size):
        widths = []
        for idx, h in enumerate(headers):
            widest = stringWidth(str(h), header_font, h_size)
            for row in rows:
                cell = str(row[idx]) if idx < len(row) and row[idx] is not None else ''
                w = stringWidth(cell, body_font, b_size)
                if w > widest:
                    widest = w
            widths.append(widest + cell_padding)
        return widths

    header_size, body_size = default_header_size, default_body_size
    widths = measure(header_size, body_size)
    total = sum(widths)

    # Shrink fonts together (keeping header slightly larger than body)
    # until the content fits on one line across the page width.
    while total > doc_width and (header_size > min_header_size or body_size > min_body_size):
        if header_size > min_header_size:
            header_size -= 0.5
        if body_size > min_body_size:
            body_size -= 0.5
        widths = measure(header_size, body_size)
        total = sum(widths)

    if total > doc_width:
        # Rare edge case: even at minimum readable font size the content
        # is wider than the page. Compress proportionally as a last resort.
        scale = doc_width / total
        widths = [w * scale for w in widths]
    else:
        # Distribute the leftover space proportionally so the table still
        # spans the full page width, rather than leaving a ragged gap.
        leftover = doc_width - total
        if total > 0:
            widths = [w + leftover * (w / total) for w in widths]

    return widths, header_size, body_size


def create_standard_table(headers, rows, doc_width):
    """
    Create a modern table with zebra rows, auto-alignment, and content-fit
    column widths so headers and cell text always render on a single line.
    
    Args:
        headers: List of column headers
        rows: List of data rows
        doc_width: Available document width
    
    Returns:
        Table object or empty message paragraph
    """
    styles = get_styles()
    
    # Handle empty table
    if not rows or len(rows) == 0:
        return Paragraph('No records available.', styles['empty'])
    
    # Size columns (and font, if needed) so nothing wraps to a second line
    col_widths, header_size, body_size = _fit_table_layout(headers, rows, doc_width)
    
    # Header style at the fitted size (white text, bold, centered)
    header_style = styles['table_header'].clone('table_header_fit')
    header_style.fontSize = header_size
    header_style.leading = header_size + 2
    
    # Body style at the fitted size - single line, no word-splitting
    body_base_style = styles['normal'].clone('table_body_fit')
    body_base_style.fontSize = body_size
    body_base_style.leading = body_size + 3
    body_base_style.splitLongWords = False
    
    # Convert headers to Paragraph objects (white text so they're legible
    # against the purple header background - must use a style with white
    # textColor since Paragraph styling overrides TableStyle TEXTCOLOR)
    wrapped_headers = []
    for h in headers:
        p = Paragraph(str(h), header_style)
        wrapped_headers.append(p)
    
    # Convert rows to Paragraph objects with auto-alignment; column widths
    # were sized to each cell's natural width so text stays on one line
    wrapped_rows = []
    for row in rows:
        wrapped_row = []
        for idx, cell in enumerate(row):
            header_name = headers[idx] if idx < len(headers) else ''
            alignment = get_column_alignment(header_name)
            cell_style = body_base_style.clone(f'cell_{idx}')
            cell_style.alignment = 0 if alignment == 'LEFT' else (1 if alignment == 'CENTER' else 2)
            p = Paragraph(str(cell) if cell else '', cell_style)
            wrapped_row.append(p)
        wrapped_rows.append(wrapped_row)
    
    # Create table data
    table_data = [wrapped_headers] + wrapped_rows
    
    # Create table
    table = Table(table_data, colWidths=col_widths, repeatRows=1)
    
    # Build table style with zebra rows
    table_style = TableStyle([
        # Header styling - purple background, white bold text
        ('BACKGROUND', (0, 0), (-1, 0), colors.HexColor('#4338CA')),
        ('TEXTCOLOR', (0, 0), (-1, 0), colors.white),
        ('ALIGN', (0, 0), (-1, 0), 'CENTER'),
        ('FONTNAME', (0, 0), (-1, 0), 'Helvetica-Bold'),
        ('FONTSIZE', (0, 0), (-1, 0), header_size),
        ('VALIGN', (0, 0), (-1, 0), 'MIDDLE'),
        ('LEFTPADDING', (0, 0), (-1, 0), 10),
        ('RIGHTPADDING', (0, 0), (-1, 0), 10),
        ('TOPPADDING', (0, 0), (-1, 0), 12),
        ('BOTTOMPADDING', (0, 0), (-1, 0), 12),
        
        # Body styling - minimum row height 28pt, zebra rows
        ('LEFTPADDING', (0, 1), (-1, -1), 10),
        ('RIGHTPADDING', (0, 1), (-1, -1), 10),
        ('TOPPADDING', (0, 1), (-1, -1), 12),
        ('BOTTOMPADDING', (0, 1), (-1, -1), 12),
        ('VALIGN', (0, 1), (-1, -1), 'MIDDLE'),
        ('MINROWHEIGHT', (0, 1), (-1, -1), 28),
        ('GRID', (0, 0), (-1, -1), 0.5, colors.HexColor('#DDDDDD')),
        ('ROWBACKGROUNDS', (0, 1), (-1, -1), [colors.white, colors.HexColor('#F8F9FA')]),
    ])
    
    # Apply per-column alignment for body rows
    for col_idx, header in enumerate(headers):
        alignment = get_column_alignment(header)
        table_style.add('ALIGN', (col_idx, 1), (col_idx, -1), alignment)
    
    table.setStyle(table_style)
    
    return table


def create_footer():
    """
    Create the footer block that appears after the table.
    
    Returns:
        List of flowables for the footer
    """
    styles = get_styles()
    elements = []
    
    elements.append(Spacer(1, 30))
    elements.append(Paragraph('Generated by EduSphere Examination System', styles['footer']))
    elements.append(Paragraph('This report is electronically generated and does not require a signature.', styles['footer']))
    
    return elements


def should_use_landscape(headers):
    """
    All non-result reports must use standard portrait A4, per requirement.
    Landscape auto-switching is disabled - always returns False.
    
    Args:
        headers: List of column headers (unused, kept for call-site compatibility)
    
    Returns:
        False, always - portrait A4 for every report
    """
    return False


def build_premium_report(title, summary, headers, rows, filename, logo_path=None):
    """
    Premium PDF builder function for all non-result reports.
    Produces enterprise-quality output with consistent design across all reports.
    
    Args:
        title: Report title (e.g., 'USERS REPORT')
        summary: List of [label, value] pairs for summary section
        headers: List of column headers
        rows: List of data rows (each row is a list of values)
        filename: Output filename
        logo_path: Optional path to logo image
    
    Returns:
        Flask Response object with PDF data
    """
    from flask import Response
    from io import BytesIO
    
    # Set footer metadata globally
    generated_time = datetime.now().strftime('%d %b %Y %I:%M %p')
    set_footer_metadata(title, generated_time)
    
    # Auto-detect landscape orientation
    use_landscape = should_use_landscape(headers)
    
    # Create PDF buffer with standard margins
    buffer = BytesIO()
    pagesize = landscape_pagesize(A4) if use_landscape else A4
    
    doc = SimpleDocTemplate(
        buffer,
        pagesize=pagesize,
        leftMargin=35,
        rightMargin=35,
        topMargin=30,
        bottomMargin=40,
    )
    
    # Calculate available document width
    doc_width = pagesize[0] - 70  # Subtract margins
    
    # Get styles
    styles = get_styles()
    
    # Build elements list
    elements = []
    
    # ===== HEADER =====
    elements.append(create_report_header(title, logo_path, doc_width))
    elements.append(Spacer(1, 15))
    
    # ===== SUMMARY =====
    if summary:
        elements.extend(create_summary_section(summary, doc_width))
    
    # ===== TABLE =====
    elements.append(create_standard_table(headers, rows, doc_width))
    
    # ===== IN-FLOW FOOTER (appears right after the table content) =====
    elements.extend(create_footer())
    
    # Build PDF (NumberedCanvas does a two-pass render so the footer can
    # show the real total page count, e.g. "Page 2 of 5")
    doc.build(elements, canvasmaker=NumberedCanvas)
    
    # Create response
    buffer.seek(0)
    response = Response(buffer.getvalue(), mimetype='application/pdf')
    response.headers['Content-Disposition'] = f'attachment; filename={filename}'
    
    return response
